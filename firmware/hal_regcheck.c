/* Compile-time only: hand-written register offsets vs the Nordic MDK.
 * Produces no code. */
#include <stddef.h>
#include "nrf52.h"
#include "hal_saadc.h"

#define CHECK(off, field) \
    _Static_assert((off) == offsetof(NRF_SAADC_Type, field), #field)

CHECK(SAADC_OFF_TASKS_START, TASKS_START);
CHECK(SAADC_OFF_TASKS_SAMPLE, TASKS_SAMPLE);
CHECK(SAADC_OFF_TASKS_STOP, TASKS_STOP);
CHECK(SAADC_OFF_EVENTS_STARTED, EVENTS_STARTED);
CHECK(SAADC_OFF_EVENTS_END, EVENTS_END);
CHECK(SAADC_OFF_EVENTS_STOPPED, EVENTS_STOPPED);
CHECK(SAADC_OFF_ENABLE, ENABLE);
CHECK(SAADC_OFF_CH0_PSELP, CH[0].PSELP);
CHECK(SAADC_OFF_CH0_PSELN, CH[0].PSELN);
CHECK(SAADC_OFF_CH0_CONFIG, CH[0].CONFIG);
CHECK(SAADC_OFF_RESOLUTION, RESOLUTION);
CHECK(SAADC_OFF_OVERSAMPLE, OVERSAMPLE);
CHECK(SAADC_OFF_SAMPLERATE, SAMPLERATE);
CHECK(SAADC_OFF_RESULT_PTR, RESULT.PTR);
CHECK(SAADC_OFF_RESULT_MAXCNT, RESULT.MAXCNT);
_Static_assert(SAADC_BASE == NRF_SAADC_BASE, "SAADC base");

