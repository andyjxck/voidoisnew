#!/usr/bin/env python3
"""Bake VoidOS assets (Kenney Future font, material icons, boot logo) into
C tables for the PineTime firmware. Output: firmware/gen/assets_data.c"""
import os
import sys
from PIL import Image, ImageFont

sys.path.insert(0, os.path.dirname(__file__))
from micons_list import ICONS as MICONS, OUT_DIR as MICONS_DIR  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
FONTS = os.path.join(ROOT, "assets", "fonts")
OUT = os.path.join(os.path.dirname(__file__), "..", "gen", "assets_data.c")
LVGL_OUT = os.path.join(os.path.dirname(__file__), "..", "gen", "kenney_lvgl.c")
MICONS_C = os.path.join(os.path.dirname(__file__), "..", "gen", "micons.c")
MICONS_H = os.path.join(os.path.dirname(__file__), "..", "gen", "micons.h")

FONT_SIZES = [9, 13, 16, 22, 24, 32, 56]
FIRST, LAST = 32, 126

LOGO = "Gemini_Generated_Image_3ig0p63ig0p63ig0-removebg-preview.png"
LOGO_PX = 112


def emit_bytes(f, data, per_line=24):
    for i in range(0, len(data), per_line):
        f.write("    " + ",".join(str(b) for b in data[i:i + per_line]) + ",\n")


def pack4(alpha_rows, w, h):
    """4-bit alpha, two pixels per byte, rows padded to even width."""
    out = bytearray()
    for y in range(h):
        row = alpha_rows[y * w:(y + 1) * w]
        for x in range(0, w, 2):
            a = row[x] >> 4
            b = (row[x + 1] >> 4) if x + 1 < w else 0
            out.append((a << 4) | b)
    return out


def bake_font(f, px):
    font = ImageFont.truetype(os.path.join(FONTS, "Kenney Future.ttf"), px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    bitmap = bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="la")
        gw, gh = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bitmap)
        if gw and gh:
            img = Image.new("L", (gw, gh), 0)
            from PIL import ImageDraw
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255,
                                     anchor="la")
            bitmap += pack4(list(img.getdata()), gw, gh)
        glyphs.append((adv, x0, y0, gw, gh, off))
    f.write(f"static const uint8_t font{px}_bits[] = {{\n")
    emit_bytes(f, bitmap or b"\0")
    f.write("};\n")
    f.write(f"static const glyph_t font{px}_glyphs[] = {{\n")
    for g in glyphs:
        f.write("    {%d,%d,%d,%d,%d,%d},\n" % g)
    f.write("};\n")
    return height, len(bitmap)


def bake_micons():
    """Google Material Symbols (assets/micons/*.png, rendered from the
    font by tools/render_micons.py) -> A8 lv_image_dsc_t tables."""
    sizes = sorted({px for _, _, _, szs in MICONS for px in szs})
    with open(MICONS_H, "w") as h:
        h.write("/* generated by tools/gen_assets.py from tools/micons_list.py"
                " — do not edit */\n#ifndef VOIDOS_GEN_MICONS_H\n"
                "#define VOIDOS_GEN_MICONS_H\n\nenum {\n")
        for ident, sym, _, _ in MICONS:
            h.write(f"    MI_{ident},  /* {sym} */\n")
        h.write("    MI_COUNT\n};\n\n")
        h.write(f"#define MI_NSIZES {len(sizes)}\n")
        h.write("static const unsigned char mi_sizes[MI_NSIZES] = {%s};\n\n"
                % ", ".join(map(str, sizes)))
        h.write("#endif\n")
    total = 0
    with open(MICONS_C, "w") as f:
        f.write("/* generated by tools/gen_assets.py — do not edit.\n"
                "   Google Material Symbols (Apache 2.0), A8 alpha */\n"
                '#include "lvgl.h"\n#include "gen/micons.h"\n\n')
        names = {}
        for ident, sym, _, szs in MICONS:
            for px in szs:
                img = Image.open(os.path.join(MICONS_DIR, f"{sym}_{px}.png"))
                img = img.convert("RGBA")
                if img.size != (px, px):
                    raise SystemExit(f"{sym}_{px}.png is {img.size}")
                a = img.getchannel("A").tobytes()
                n = f"mi_{sym}_{px}"
                f.write(f"static const uint8_t {n}_a8[] = {{\n")
                emit_bytes(f, a)
                f.write("};\n")
                f.write(f"static const lv_image_dsc_t {n} = {{.header = {{"
                        f".magic = LV_IMAGE_HEADER_MAGIC, "
                        f".cf = LV_COLOR_FORMAT_A8, .w = {px}, .h = {px}, "
                        f".stride = {px}}}, .data_size = {px * px}, "
                        f".data = {n}_a8}};\n")
                names[(ident, px)] = n
                total += px * px
        f.write("\nconst lv_image_dsc_t *const micon_tab[MI_COUNT][MI_NSIZES]"
                " = {\n")
        for ident, _, _, _ in MICONS:
            row = [("&" + names[(ident, px)]) if (ident, px) in names
                   else "NULL" for px in sizes]
            f.write(f"    [MI_{ident}] = {{{', '.join(row)}}},\n")
        f.write("};\n")
    print(f"wrote {MICONS_C}: {len(names)} icons, {total // 1024} KB")


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    bake_micons()
    total = 0
    with open(OUT, "w") as f:
        f.write("/* generated by tools/gen_assets.py — do not edit */\n")
        f.write('#include "assets.h"\n\n')
        heights = []
        for px in FONT_SIZES:
            h, n = bake_font(f, px)
            heights.append(h)
            total += n
        f.write("const font_t fonts[] = {\n")
        for px, h in zip(FONT_SIZES, heights):
            f.write(f"    {{{px}, {h}, font{px}_glyphs, font{px}_bits}},\n")
        f.write("};\nconst int font_count = %d;\n\n" % len(FONT_SIZES))

        img = Image.open(os.path.join(FONTS, LOGO)).convert("RGBA")
        img = img.resize((LOGO_PX, LOGO_PX), Image.LANCZOS)
        rgb, alpha = bytearray(), bytearray()
        for r, g, b, a in img.getdata():
            v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
            rgb += bytes((v & 0xFF, v >> 8))
            alpha.append(a)
        f.write(f"const uint16_t logo_rgb[{LOGO_PX * LOGO_PX}] = {{\n")
        for i in range(0, len(rgb), 32):
            chunk = rgb[i:i + 32]
            words = [chunk[j] | (chunk[j + 1] << 8) for j in range(0, len(chunk), 2)]
            f.write("    " + ",".join("0x%04x" % w for w in words) + ",\n")
        f.write("};\n")
        f.write(f"const uint8_t logo_alpha[{LOGO_PX * LOGO_PX}] = {{\n")
        emit_bytes(f, alpha)
        f.write("};\n")
        total += len(rgb) + len(alpha)
    print(f"wrote {OUT}: ~{total // 1024} KB of asset data")

    with open(LVGL_OUT, "w") as f:
        f.write('#include "lvgl.h"\n#include "src/font/lv_font_fmt_txt.h"\n\n')
        for px in (9, 12, 16, 24, 56, 72):
            # 2.2.3: the 56 px face/cardio digits only ever draw "-./0-9:"
            # (45..58); the full ASCII set cost 67 KB of flash.
            # 2.2.5: 72 px is the face's hours, the same digits-only set
            first, last = (45, 58) if px >= 56 else (FIRST, LAST)
            font = ImageFont.truetype(os.path.join(FONTS, "Kenney Future.ttf"), px)
            ascent, descent = font.getmetrics()
            glyphs, bitmap = [(0, 0, 0, 0, 0, 0)], bytearray()
            for code in range(first, last + 1):
                ch = chr(code)
                adv = int(round(font.getlength(ch)))
                x0, y0, x1, y1 = font.getbbox(ch, anchor="la")
                gw, gh = max(0, x1 - x0), max(0, y1 - y0)
                off = len(bitmap)
                if gw and gh:
                    img = Image.new("L", (gw, gh), 0)
                    from PIL import ImageDraw
                    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font,
                                             fill=255, anchor="la")
                    pixels = list(img.getdata())
                    bitmap.extend(((pixels[i] >> 4) << 4) |
                                  (pixels[i + 1] >> 4 if i + 1 < len(pixels) else 0)
                                  for i in range(0, len(pixels), 2))
                glyphs.append((off, adv * 16, gw, gh, x0, ascent - y0 - gh))
            f.write(f"static const uint8_t kenney{px}_bits[] = {{\n")
            emit_bytes(f, bitmap or b"\0")
            f.write("};\n")
            f.write(f"static const lv_font_fmt_txt_glyph_dsc_t kenney{px}_glyphs[] = {{\n")
            for g in glyphs:
                f.write("    {%d,%d,%d,%d,%d,%d},\n" % g)
            f.write("};\n")
            f.write(f"static const lv_font_fmt_txt_cmap_t kenney{px}_cmap = {{"
                    f".range_start = {first}, .range_length = {last - first + 1}, "
                    ".glyph_id_start = 1, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY};\n")
            f.write(f"static const lv_font_fmt_txt_dsc_t kenney{px}_dsc = {{"
                    f".glyph_bitmap = kenney{px}_bits, .glyph_dsc = kenney{px}_glyphs, "
                    f".cmaps = &kenney{px}_cmap, .cmap_num = 1, .bpp = 4}};\n")
            f.write(f"const lv_font_t kenney{px} = {{"
                    ".get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, "
                    ".get_glyph_bitmap = lv_font_get_bitmap_fmt_txt, "
                    f".line_height = {ascent + descent}, .base_line = {descent}, "
                    f".dsc = &kenney{px}_dsc}};\n\n")
    print(f"wrote {LVGL_OUT}")


if __name__ == "__main__":
    sys.exit(main())
